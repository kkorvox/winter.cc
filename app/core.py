
import os
import secrets
import hashlib
import random
import string
import time
import re
from contextlib import contextmanager
from datetime import datetime, timezone

import bcrypt
import psycopg
from psycopg.rows import dict_row

DATABASE_URL = os.environ["DATABASE_URL"]

WORDS = [
    "void", "ghost", "chrome", "angel", "vex", "nova",
    "frost", "pixel", "night", "lunar", "zero", "echo",
    "haze", "orbit", "drift", "glow", "shade", "storm",
    "azure", "bliss", "velvet", "static", "raven",
    "onyx", "winter"
]

RULES = {
    "Discord": (2, 32, set(string.ascii_lowercase + string.digits + "._")),
    "Roblox": (3, 20, set(string.ascii_letters + string.digits + "_")),
    "Instagram": (1, 30, set(string.ascii_letters + string.digits + "._")),
    "TikTok": (2, 24, set(string.ascii_letters + string.digits + "._")),
    "Telegram": (5, 32, set(string.ascii_letters + string.digits + "_")),
    "Minecraft": (3, 16, set(string.ascii_letters + string.digits + "_")),
}


def now():
    return datetime.now(timezone.utc).isoformat()


@contextmanager
def db():
    with psycopg.connect(
        DATABASE_URL,
        row_factory=dict_row,
        connect_timeout=15
    ) as conn:
        yield conn


def init():
    with db() as conn:
        conn.execute("""
            CREATE TABLE IF NOT EXISTS users (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                username TEXT NOT NULL,
                password BYTEA NOT NULL,
                is_admin INTEGER NOT NULL DEFAULT 0
            )
        """)

        conn.execute("""
            CREATE UNIQUE INDEX IF NOT EXISTS
            users_username_lower_unique
            ON users (LOWER(username))
        """)

        conn.execute("""
            CREATE TABLE IF NOT EXISTS licenses (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                key_hash TEXT UNIQUE NOT NULL,
                user_id BIGINT NOT NULL
                    REFERENCES users(id) ON DELETE CASCADE,
                revoked INTEGER NOT NULL DEFAULT 0,
                expires_at TEXT
            )
        """)

        conn.execute("""
            CREATE TABLE IF NOT EXISTS sessions (
                token_hash TEXT PRIMARY KEY,
                user_id BIGINT NOT NULL
                    REFERENCES users(id) ON DELETE CASCADE,
                expires DOUBLE PRECISION NOT NULL
            )
        """)

        conn.execute("""
            CREATE TABLE IF NOT EXISTS searches (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id BIGINT REFERENCES users(id) ON DELETE CASCADE,
                platform TEXT,
                created TEXT
            )
        """)

        conn.execute("""
            CREATE TABLE IF NOT EXISTS results (
                search_id BIGINT NOT NULL
                    REFERENCES searches(id) ON DELETE CASCADE,
                username TEXT NOT NULL,
                status TEXT,
                PRIMARY KEY (search_id, username)
            )
        """)

        conn.execute("""
            CREATE TABLE IF NOT EXISTS favorites (
                user_id BIGINT NOT NULL
                    REFERENCES users(id) ON DELETE CASCADE,
                platform TEXT NOT NULL,
                username TEXT NOT NULL,
                PRIMARY KEY (user_id, platform, username)
            )
        """)

        conn.execute("""
            CREATE TABLE IF NOT EXISTS presets (
                user_id BIGINT NOT NULL
                    REFERENCES users(id) ON DELETE CASCADE,
                name TEXT NOT NULL,
                config TEXT NOT NULL,
                PRIMARY KEY (user_id, name)
            )
        """)

        conn.execute("""
            CREATE TABLE IF NOT EXISTS check_state (
                user_id BIGINT NOT NULL
                    REFERENCES users(id) ON DELETE CASCADE,
                platform TEXT NOT NULL,
                previous_search BIGINT
                    REFERENCES searches(id) ON DELETE SET NULL,
                PRIMARY KEY (user_id, platform)
            )
        """)


def hash_key(key):
    return hashlib.sha256(key.encode()).hexdigest()


def create_user(username, password, admin=False):
    username = username.strip()

    if not re.fullmatch(r"[a-zA-Z0-9_]{3,32}", username):
        raise ValueError("Invalid username")

    if len(password) < 12:
        raise ValueError("Password must be at least 12 characters")

    hashed = bcrypt.hashpw(
        password.encode(),
        bcrypt.gensalt()
    )

    with db() as conn:
        row = conn.execute(
            """INSERT INTO users(username,password,is_admin)
               VALUES(%s,%s,%s)
               RETURNING id""",
            (username, hashed, int(admin))
        ).fetchone()

        return row["id"]


def create_license(user_id, expires_at=None):
    key = "WCC-" + secrets.token_urlsafe(24)

    with db() as conn:
        conn.execute(
            """INSERT INTO licenses(key_hash,user_id,expires_at)
               VALUES(%s,%s,%s)""",
            (hash_key(key), user_id, expires_at)
        )

    return key


def setup_owner():
    username = os.getenv("WINTER_OWNER_USERNAME")
    password = os.getenv("WINTER_OWNER_PASSWORD")
    license_key = os.getenv("WINTER_OWNER_LICENSE")

    if not all((username, password, license_key)):
        raise RuntimeError(
            "Owner environment variables are missing"
        )

    if not re.fullmatch(r"[a-zA-Z0-9_]{3,32}", username):
        raise ValueError("Invalid owner username")

    if len(password) < 12:
        raise ValueError(
            "Owner password must be at least 12 characters"
        )

    if len(license_key) < 24:
        raise ValueError(
            "Owner license must be at least 24 characters"
        )

    with db() as conn:
        conn.execute(
            "SELECT pg_advisory_xact_lock(847211)"
        )

        owner = conn.execute(
            """SELECT id,is_admin FROM users
               WHERE LOWER(username)=LOWER(%s)""",
            (username,)
        ).fetchone()

        if owner:
            if not owner["is_admin"]:
                raise ValueError(
                    "Owner username belongs to a non-admin user"
                )
            user_id = owner["id"]
        else:
            hashed = bcrypt.hashpw(
                password.encode(),
                bcrypt.gensalt()
            )

            row = conn.execute(
                """INSERT INTO users
                   (username,password,is_admin)
                   VALUES(%s,%s,1)
                   RETURNING id""",
                (username, hashed)
            ).fetchone()

            user_id = row["id"]

        key_hash = hash_key(license_key)

        existing = conn.execute(
            """SELECT user_id FROM licenses
               WHERE key_hash=%s""",
            (key_hash,)
        ).fetchone()

        if existing and existing["user_id"] != user_id:
            raise ValueError(
                "Owner license belongs to another user"
            )

        if not existing:
            conn.execute(
                """INSERT INTO licenses
                   (key_hash,user_id)
                   VALUES(%s,%s)""",
                (key_hash, user_id)
            )


def auth(username, password, key):
    with db() as conn:
        user = conn.execute(
            """SELECT * FROM users
               WHERE LOWER(username)=LOWER(%s)""",
            (username,)
        ).fetchone()

        if not user:
            return None

        if not bcrypt.checkpw(
            password.encode(),
            bytes(user["password"])
        ):
            return None

        license_row = conn.execute(
            """SELECT * FROM licenses
               WHERE key_hash=%s
               AND user_id=%s
               AND revoked=0""",
            (hash_key(key), user["id"])
        ).fetchone()

        if not license_row:
            return None

        if (
            license_row["expires_at"]
            and license_row["expires_at"] <= now()
        ):
            return None

        token = secrets.token_urlsafe(32)

        conn.execute(
            """INSERT INTO sessions
               (token_hash,user_id,expires)
               VALUES(%s,%s,%s)""",
            (
                hash_key(token),
                user["id"],
                time.time() + 12 * 3600
            )
        )

        return token


def current_user(token):
    with db() as conn:
        row = conn.execute(
            """SELECT u.id,u.username,u.is_admin
               FROM sessions s
               JOIN users u ON u.id=s.user_id
               WHERE s.token_hash=%s
               AND s.expires>%s
               AND EXISTS (
                   SELECT 1 FROM licenses l
                   WHERE l.user_id=u.id
                   AND l.revoked=0
                   AND (
                       l.expires_at IS NULL
                       OR l.expires_at>%s
                   )
               )""",
            (hash_key(token), time.time(), now())
        ).fetchone()

        return dict(row) if row else None


def candidates(
    platform,
    lengths,
    types,
    characters,
    prefix,
    suffix,
    count,
    wordlist=None
):
    if platform not in RULES:
        raise ValueError("Unsupported platform")

    minimum, maximum, allowed = RULES[platform]

    lengths = [
        int(x) for x in lengths
        if str(x).isdigit()
        and minimum <= int(x) <= maximum
    ]

    if not lengths:
        raise ValueError("No valid lengths")

    if not 1 <= count <= 100000:
        raise ValueError("Invalid amount")

    selections = [
        ("Lowercase", string.ascii_lowercase),
        ("Uppercase", string.ascii_uppercase),
        ("Numbers", string.digits),
        ("Underscores", "_"),
        ("Periods", ".")
    ]

    pool = "".join(
        chars for name, chars in selections
        if name in characters
    )

    pool = "".join(sorted(set(pool) & allowed))

    if not pool:
        raise ValueError(
            "No permitted characters selected"
        )

    if any(char not in allowed for char in prefix + suffix):
        raise ValueError("Invalid prefix or suffix")

    if len(prefix) + len(suffix) > max(lengths):
        raise ValueError(
            "Prefix and suffix are too long"
        )

    types = types or ["Random letters"]

    words = [
        word.strip()
        for word in (wordlist or WORDS)
        if isinstance(word, str) and word.strip()
    ]

    words = [
        word for word in words
        if all(char in allowed for char in word)
    ] or WORDS

    rng = random.SystemRandom()
    seen = set()
    output = []
    attempts = 0

    consonants = "bcdfghjklmnpqrstvwxyz"
    vowels = "aeiou"

    while (
        len(output) < count
        and attempts < max(1000, count * 35)
    ):
        attempts += 1

        size = rng.choice(lengths)
        middle = size - len(prefix) - len(suffix)

        if middle < 0:
            continue

        mode = rng.choice(types)

        if mode == "Numbers only":
            base = "".join(
                rng.choices(string.digits, k=middle)
            )

        elif mode in ("Real words / OG", "Aesthetic"):
            word = rng.choice(words)
            base = (
                word[:middle]
                if len(word) >= middle
                else word + "".join(
                    rng.choices(
                        pool,
                        k=middle - len(word)
                    )
                )
            )

        elif mode == "Pronounceable":
            base = "".join(
                rng.choice(
                    consonants if i % 2 == 0 else vowels
                )
                for i in range(middle)
            )

        elif mode == "Letters + numbers":
            mixed = "".join(
                char for char in pool
                if char.isalnum()
            )
            base = "".join(
                rng.choices(mixed or pool, k=middle)
            )

        else:
            base = "".join(
                rng.choices(pool, k=middle)
            )

        name = prefix + base + suffix

        if platform == "Discord":
            name = name.lower()

        if len(name) not in lengths:
            continue

        if any(char not in allowed for char in name):
            continue

        if name not in seen:
            seen.add(name)
            output.append(name)

    return output


def start_search(user_id, platform, names):
    if platform not in RULES:
        raise ValueError("Unsupported platform")

    names = list(dict.fromkeys(names))

    with db() as conn:
        previous = conn.execute(
            """SELECT previous_search
               FROM check_state
               WHERE user_id=%s AND platform=%s""",
            (user_id, platform)
        ).fetchone()

        skipped = set()

        if previous and previous["previous_search"]:
            skipped = {
                row["username"]
                for row in conn.execute(
                    """SELECT username FROM results
                       WHERE search_id=%s AND status=%s""",
                    (
                        previous["previous_search"],
                        "available"
                    )
                )
            }

        row = conn.execute(
            """INSERT INTO searches
               (user_id,platform,created)
               VALUES(%s,%s,%s)
               RETURNING id""",
            (user_id, platform, now())
        ).fetchone()

        search_id = row["id"]

        rows = [
            {
                "username": name,
                "status": (
                    "skipped"
                    if name in skipped
                    else "unknown"
                )
            }
            for name in names
        ]

        conn.executemany(
            """INSERT INTO results
               (search_id,username,status)
               VALUES(%s,%s,%s)""",
            [
                (
                    search_id,
                    row["username"],
                    row["status"]
                )
                for row in rows
            ]
        )

        conn.execute(
            """INSERT INTO check_state
               (user_id,platform,previous_search)
               VALUES(%s,%s,%s)
               ON CONFLICT(user_id,platform)
               DO UPDATE SET
               previous_search=excluded.previous_search""",
            (user_id, platform, search_id)
        )

    return search_id, rows
