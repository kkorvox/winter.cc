def now():
    return datetime.now(timezone.utc).isoformat()


@contextmanager
def db():
    with psycopg.connect(
        DATABASE_URL,
        row_factory=dict_row,
        connect_timeout=15
    ) as conn:
        yield conn


def init():
    with db() as conn:
        conn.execute('''
            CREATE TABLE IF NOT EXISTS users (
                id BIGINT GENERATED BY DEFAULT
                    AS IDENTITY PRIMARY KEY,
                username TEXT NOT NULL,
                password BYTEA NOT NULL,
                is_admin INTEGER NOT NULL DEFAULT 0
            )
        ''')

        conn.execute('''
            CREATE UNIQUE INDEX IF NOT EXISTS
                users_username_lower_unique
            ON users (LOWER(username))
        ''')

        for column in (
            'created_at TEXT',
            'last_login TEXT',
            'login_count INTEGER NOT NULL DEFAULT 0',
            'suspended INTEGER NOT NULL DEFAULT 0'
        ):
            conn.execute(
                'ALTER TABLE users ADD COLUMN IF NOT EXISTS '
                + column
            )

        conn.execute('''
            CREATE TABLE IF NOT EXISTS licenses (
                id BIGINT GENERATED BY DEFAULT
                    AS IDENTITY PRIMARY KEY,
                key_hash TEXT UNIQUE NOT NULL,
                user_id BIGINT NOT NULL
                    REFERENCES users(id) ON DELETE CASCADE,
                revoked INTEGER NOT NULL DEFAULT 0,
                expires_at TEXT
            )
        ''')

        conn.execute('''
            CREATE TABLE IF NOT EXISTS sessions (
                token_hash TEXT PRIMARY KEY,
                user_id BIGINT NOT NULL
                    REFERENCES users(id) ON DELETE CASCADE,
                expires DOUBLE PRECISION NOT NULL
            )
        ''')

        conn.execute('''
            CREATE TABLE IF NOT EXISTS searches (
                id BIGINT GENERATED BY DEFAULT
                    AS IDENTITY PRIMARY KEY,
                user_id BIGINT
                    REFERENCES users(id) ON DELETE CASCADE,
                platform TEXT,
                created TEXT
            )
        ''')

        conn.execute('''
            CREATE TABLE IF NOT EXISTS results (
                search_id BIGINT NOT NULL
                    REFERENCES searches(id) ON DELETE CASCADE,
                username TEXT NOT NULL,
                status TEXT,
                PRIMARY KEY(search_id, username)
            )
        ''')

        conn.execute('''
            CREATE TABLE IF NOT EXISTS favorites (
                user_id BIGINT NOT NULL
                    REFERENCES users(id) ON DELETE CASCADE,
                platform TEXT NOT NULL,
                username TEXT NOT NULL,
                PRIMARY KEY(user_id, platform, username)
            )
        ''')

        conn.execute('''
            CREATE TABLE IF NOT EXISTS presets (
                user_id BIGINT NOT NULL
                    REFERENCES users(id) ON DELETE CASCADE,
                name TEXT NOT NULL,
                config TEXT NOT NULL,
                PRIMARY KEY(user_id, name)
            )
        ''')

        conn.execute('''
            CREATE TABLE IF NOT EXISTS check_state (
                user_id BIGINT NOT NULL
                    REFERENCES users(id) ON DELETE CASCADE,
                platform TEXT NOT NULL,
                previous_search BIGINT
                    REFERENCES searches(id) ON DELETE SET NULL,
                PRIMARY KEY(user_id, platform)
            )
        ''')

        conn.execute('''
            CREATE TABLE IF NOT EXISTS activity (
                id BIGINT GENERATED BY DEFAULT
                    AS IDENTITY PRIMARY KEY,
                user_id BIGINT NOT NULL
                    REFERENCES users(id) ON DELETE CASCADE,
                action TEXT NOT NULL,
                details TEXT,
                created TEXT NOT NULL
            )
        ''')

        conn.execute('''
            CREATE INDEX IF NOT EXISTS
                activity_user_created_idx
            ON activity(user_id, id DESC)
        ''')

        conn.execute('''
            CREATE INDEX IF NOT EXISTS
                activity_created_idx
            ON activity(id DESC)
        ''')


def hash_key(key):
    return hashlib.sha256(key.encode()).hexdigest()


def log_activity(user_id, action, details=None):
    with db() as conn:
        conn.execute('''
            INSERT INTO activity (
                user_id, action, details, created
            )
            VALUES (%s, %s, %s, %s)
        ''', (user_id, action, details, now()))


def create_user(username, password, admin=False):
    username = username.strip()

    if not re.fullmatch(r'[a-zA-Z0-9_]{3,32}', username):
        raise ValueError('Invalid username')

    if len(password) < 12:
        raise ValueError(
            'Password must be at least 12 characters'
        )

    hashed = bcrypt.hashpw(
        password.encode(),
        bcrypt.gensalt()
    )

    with db() as conn:
        row = conn.execute('''
            INSERT INTO users (
                username, password, is_admin, created_at
            )
            VALUES (%s, %s, %s, %s)
            RETURNING id
        ''', (
            username,
            hashed,
            int(admin),
            now()
        )).fetchone()

        return row['id']


def create_license(user_id, expires_at=None):
    key = 'WCC-' + secrets.token_urlsafe(24)

    with db() as conn:
        conn.execute('''
            INSERT INTO licenses (
                key_hash, user_id, expires_at
            )
            VALUES (%s, %s, %s)
        ''', (
            hash_key(key),
            user_id,
            expires_at
        ))

    return key


def setup_owner():
    username = os.getenv('WINTER_OWNER_USERNAME')
    password = os.getenv('WINTER_OWNER_PASSWORD')
    license_key = os.getenv('WINTER_OWNER_LICENSE')

    if not all((username, password, license_key)):
        raise RuntimeError(
            'Owner environment variables are missing'
        )

    if not re.fullmatch(
        r'[a-zA-Z0-9_]{3,32}',
        username
    ):
        raise ValueError('Invalid owner username')

    if len(password) < 12:
        raise ValueError(
            'Owner password must be at least 12 characters'
        )

    if len(license_key) < 24:
        raise ValueError(
            'Owner license must be at least 24 characters'
        )

    with db() as conn:
        conn.execute(
            'SELECT pg_advisory_xact_lock(847211)'
        )

        owner = conn.execute('''
            SELECT id, is_admin
            FROM users
            WHERE LOWER(username) = LOWER(%s)
        ''', (username,)).fetchone()

        if owner:
            if not owner['is_admin']:
                raise ValueError(
                    'Owner username belongs to a non-admin user'
                )

            user_id = owner['id']

        else:
            hashed = bcrypt.hashpw(
                password.encode(),
                bcrypt.gensalt()
            )

            row = conn.execute('''
                INSERT INTO users (
                    username,
                    password,
                    is_admin,
                    created_at
                )
                VALUES (%s, %s, 1, %s)
                RETURNING id
            ''', (
                username,
                hashed,
                now()
            )).fetchone()

            user_id = row['id']

        key_hash = hash_key(license_key)

        existing = conn.execute('''
            SELECT user_id
            FROM licenses
            WHERE key_hash = %s
        ''', (key_hash,)).fetchone()

        if existing and existing['user_id'] != user_id:
            raise ValueError(
                'Owner license belongs to another user'
            )

        if not existing:
            conn.execute('''
                INSERT INTO licenses (
                    key_hash, user_id
                )
                VALUES (%s, %s)
            ''', (key_hash, user_id))


def auth(username, password, key):
    with db() as conn:
        user = conn.execute('''
            SELECT *
            FROM users
            WHERE LOWER(username) = LOWER(%s)
        ''', (username,)).fetchone()

        if not user or user['suspended']:
            return None

        if not bcrypt.checkpw(
            password.encode(),
            bytes(user['password'])
        ):
            return None

        license_row = conn.execute('''
            SELECT *
            FROM licenses
            WHERE key_hash = %s
              AND user_id = %s
              AND revoked = 0
        ''', (
            hash_key(key),
            user['id']
        )).fetchone()

        if not license_row:
            return None

        if (
            license_row['expires_at']
            and license_row['expires_at'] <= now()
        ):
            return None

        token = secrets.token_urlsafe(32)

        conn.execute('''
            INSERT INTO sessions (
                token_hash, user_id, expires
            )
            VALUES (%s, %s, %s)
        ''', (
            hash_key(token),
            user['id'],
            time.time() + 12 * 3600
        ))

        conn.execute('''
            UPDATE users
            SET last_login = %s,
                login_count = login_count + 1
            WHERE id = %s
        ''', (
            now(),
            user['id']
        ))

        conn.execute('''
            INSERT INTO activity (
                user_id, action, details, created
            )
            VALUES (%s, %s, %s, %s)
        ''', (
            user['id'],
            'login',
            'Successful login',
            now()
        ))

        return token


def current_user(token):
    with db() as conn:
        row = conn.execute('''
            SELECT
                u.id,
                u.username,
                u.is_admin
            FROM sessions s
            JOIN users u ON u.id = s.user_id
            WHERE s.token_hash = %s
              AND s.expires > %s
              AND u.suspended = 0
              AND EXISTS (
                  SELECT 1
                  FROM licenses l
                  WHERE l.user_id = u.id
                    AND l.revoked = 0
                    AND (
                        l.expires_at IS NULL
                        OR l.expires_at > %s
                    )
              )
        ''', (
            hash_key(token),
            time.time(),
            now()
        )).fetchone()

        return dict(row) if row else None


def valid_platform_name(platform, name):
    if platform not in RULES:
        return False

    if not isinstance(name, str):
        return False

    minimum, maximum, allowed = RULES[platform]

    if not minimum <= len(name) <= maximum:
        return False

    if any(char not in allowed for char in name):
        return False

    if platform == 'Discord':
        return (
            name == name.lower()
            and '..' not in name
        )

    if platform == 'Roblox':
        return (
            not name.startswith('_')
            and not name.endswith('_')
            and name.count('_') <= 1
        )

    if platform in ('Instagram', 'TikTok'):
        return not name.endswith('.')

    if platform == 'Telegram':
        return name[0].isalpha()

    return True


def pronounceable(rng, size):
    return ''.join(
        rng.choice(
            CONSONANTS if i % 2 == 0 else VOWELS
        )
        for i in range(size)
    )


def random_base(rng, pool, size):
    return ''.join(
        rng.choices(pool, k=size)
    )


def fit_word(rng, words, size, pool):
    exact = [
        word
        for word in words
        if len(word) == size
    ]

    if exact:
        return rng.choice(exact)

    shorter = [
        word
        for word in words
        if len(word) < size
    ]

    if shorter:
        word = rng.choice(shorter)
        remainder = size - len(word)

        if remainder <= 3:
            return (
                word
                + random_base(rng, pool, remainder)
            )

    return None


def aesthetic_base(rng, size):
    options = [
        a + b
        for a in AESTHETIC_PARTS
        for b in AESTHETIC_PARTS
        if len(a) + len(b) == size
    ]

    return rng.choice(options) if options else None


def candidates(
    platform,
    lengths,
    types,
    characters,
    prefix,
    suffix,
    count,
    wordlist=None
):
    if platform not in RULES:
        raise ValueError('Unsupported platform')

    minimum, maximum, allowed = RULES[platform]

    lengths = sorted({
        int(x)
        for x in lengths
        if str(x).isdigit()
        and minimum <= int(x) <= maximum
    })

    if not lengths:
        raise ValueError('No valid lengths')

    if not 1 <= count <= 100000:
        raise ValueError('Invalid amount')

    selections = [
        ('Lowercase', string.ascii_lowercase),
        ('Uppercase', string.ascii_uppercase),
        ('Numbers', string.digits),
        ('Underscores', '_'),
        ('Periods', '.')
    ]

    pool = ''.join(
        value
        for label, value in selections
        if label in characters
    )

    pool = ''.join(
        sorted(set(pool) & allowed)
    )

    if not pool:
        raise ValueError(
            'No permitted characters selected'
        )

    if platform == 'Discord':
        prefix = prefix.lower()
        suffix = suffix.lower()

    if any(
        char not in allowed
        for char in prefix + suffix
    ):
        raise ValueError(
            'Invalid prefix or suffix'
        )

    if len(prefix) + len(suffix) > max(lengths):
        raise ValueError(
            'Prefix and suffix are too long'
        )

    types = types or ['Random letters']

    supplied_words = (
        wordlist if wordlist else WORDS
    )

    words = [
        word.strip()
        for word in supplied_words
        if isinstance(word, str)
        and word.strip()
        and all(
            char in allowed
            for char in word.strip()
        )
    ]

    if not words:
        words = [
            word
            for word in WORDS
            if all(
                char in allowed
                for char in word
            )
        ]

    rng = random.SystemRandom()
    seen = set()
    output = []
    attempts = 0
    maximum_attempts = max(
        2000,
        count * 45
    )

    while (
        len(output) < count
        and attempts < maximum_attempts
    ):
        attempts += 1

        size = rng.choice(lengths)
        middle = (
            size - len(prefix) - len(suffix)
        )

        if middle < 0:
            continue

        mode = rng.choice(types)

        if mode == 'Numbers only':
            base = random_base(
                rng,
                string.digits,
                middle
            )

        elif mode == 'Real words / OG':
            base = fit_word(
                rng,
                words,
                middle,
                pool
            )

            if base is None:
                base = pronounceable(
                    rng,
                    middle
                )

        elif mode == 'Aesthetic':
            base = aesthetic_base(
                rng,
                middle
            )

            if base is None:
                base = pronounceable(
                    rng,
                    middle
                )

        elif mode == 'Pronounceable':
            base = pronounceable(
                rng,
                middle
            )

        elif mode == 'Letters + numbers':
            mixed = ''.join(
                char
                for char in pool
                if char.isalnum()
            )

            base = random_base(
                rng,
                mixed or pool,
                middle
            )

        else:
            base = random_base(
                rng,
                pool,
                middle
            )

        name = prefix + base + suffix

        if platform == 'Discord':
            name = name.lower()

        if len(name) not in lengths:
            continue

        if not valid_platform_name(
            platform,
            name
        ):
            continue

        if name not in seen:
            seen.add(name)
            output.append(name)

    return output


def start_search(user_id, platform, names):
    if platform not in RULES:
        raise ValueError('Unsupported platform')

    names = list(dict.fromkeys(names))

    with db() as conn:
        previous = conn.execute('''
            SELECT previous_search
            FROM check_state
            WHERE user_id = %s
              AND platform = %s
        ''', (
            user_id,
            platform
        )).fetchone()

        skipped = set()

        if (
            previous
            and previous['previous_search']
        ):
            skipped = {
                row['username']
                for row in conn.execute('''
                    SELECT username
                    FROM results
                    WHERE search_id = %s
                      AND status = %s
                ''', (
                    previous['previous_search'],
                    'available'
                ))
            }

        row = conn.execute('''
            INSERT INTO searches (
                user_id, platform, created
            )
            VALUES (%s, %s, %s)
            RETURNING id
        ''', (
            user_id,
            platform,
            now()
        )).fetchone()

        search_id = row['id']

        rows = [
            {
                'username': name,
                'status': (
                    'skipped'
                    if name in skipped
                    else 'unknown'
                )
            }
            for name in names
        ]

        if rows:
            with conn.cursor() as cursor:
                cursor.executemany('''
                    INSERT INTO results (
                        search_id,
                        username,
                        status
                    )
                    VALUES (%s, %s, %s)
                ''', [
                    (
                        search_id,
                        item['username'],
                        item['status']
                    )
                    for item in rows
                ])

        conn.execute('''
            INSERT INTO check_state (
                user_id,
                platform,
                previous_search
            )
            VALUES (%s, %s, %s)
            ON CONFLICT(user_id, platform)
            DO UPDATE SET
                previous_search =
                    excluded.previous_search
        ''', (
            user_id,
            platform,
            search_id
        ))

        conn.execute('''
            INSERT INTO activity (
                user_id,
                action,
                details,
                created
            )
            VALUES (%s, %s, %s, %s)
        ''', (
            user_id,
            'manual_check',
            f'{platform}: {len(rows)} usernames',
            now()
        ))

    return search_id, rows
